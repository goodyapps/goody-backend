# ── helpers ──────────────────────────────────────────────────────────────────

def e(id_, input_value, brand, model, category, difficulty,
      correct, incorrect, must_not=None, input_type="text"):
    return {
        "id": id_,
        "input_type": input_type,
        "input_value": input_value,
        "expected_brand": brand,
        "expected_model_or_set_number": model,
        "expected_category": category,
        "difficulty": difficulty,
        "correct_listings": correct,
        "incorrect_listings": incorrect,
        "must_not_match": must_not or [],
    }

def lego(set_num, theme, name, extra_correct=None, extra_incorrect=None, difficulty="easy"):
    q = f"LEGO {theme} {set_num}" if theme else f"LEGO {set_num}"
    correct = [
        f"LEGO {theme} {set_num} {name}",
        f"LEGO {set_num} {name}",
        f"LEGO {set_num} {theme} {name}",
    ] + (extra_correct or [])
    incorrect = [
        f"LEGO {set_num} LED light kit",
        f"Display stand for LEGO {set_num}",
        f"Storage box LEGO {theme} {set_num}",
    ] + (extra_incorrect or [])
    must_not = [
        f"LEGO {set_num} compatible lighting kit",
        f"Minifigures from LEGO {set_num}",
    ]
    return e(f"lego_{set_num}", q, "LEGO", set_num, "lego", difficulty,
             correct, incorrect, must_not)

def phone(id_, brand, model, q, correct, incorrect, difficulty="easy"):
    must_not = [f"{model} case only", f"screen protector {brand} {model}"]
    return e(id_, q, brand, model, "electronics", difficulty, correct, incorrect, must_not)

def generic(id_, q, brand, category="generic", difficulty="easy",
            correct=None, incorrect=None):
    return e(id_, q, brand, None, category, difficulty, correct or [], incorrect or [])


